class _Ctx:
    """Mutable evaluation context (internal)."""

    def __init__(self, latest: Mapping[Tuple[str, str], Any]):
        self.latest: Dict[Tuple[str, str], LatestValue] = {
            tuple(k): _coerce_latest(v) for k, v in latest.items()  # type: ignore[misc]
        }
        self.flags: List[Flag] = []
        self.normal: List[str] = []
        self.evaluated = 0

    def get(self, key: Tuple[str, str]) -> Optional[LatestValue]:
        return self.latest.get(key)

    def get_group(self, keys: Sequence[Tuple[str, str]]) -> Optional[Tuple[Tuple[str, str], LatestValue]]:
        """Most recent LatestValue among several keys (by event_time; ties -> later key in list)."""
        best: Optional[Tuple[Tuple[str, str], LatestValue]] = None
        for k in keys:
            lv = self.latest.get(k)
            if lv is None:
                continue
            if best is None or _sort_time(lv.event_time) >= _sort_time(best[1].event_time):
                best = (k, lv)
        return best

    def add(self, flag: Flag) -> None:
        self.flags.append(flag)

    def has(self, *codes: str) -> bool:
        present = {f.code for f in self.flags}
        return any(c in present for c in codes)


def _eval_blood_pressure(ctx: _Ctx) -> None:
    sys_lv, dia_lv = ctx.get(K_BP_SYS), ctx.get(K_BP_DIA)
    sbp = _num(sys_lv.value) if sys_lv else None
    dbp = _num(dia_lv.value) if dia_lv else None
    if sbp is None and dbp is None:
        return
    ctx.evaluated += int(sbp is not None) + int(dbp is not None)
    T = THRESHOLDS
    bp_txt = f"{_fmt(sbp) if sbp is not None else '?'}/{_fmt(dbp) if dbp is not None else '?'} mmHg"

    severe = (sbp is not None and sbp >= T["bp_systolic_severe"]) or (dbp is not None and dbp >= T["bp_diastolic_severe"])
    elevated = (sbp is not None and sbp >= T["bp_systolic_elevated"]) or (dbp is not None and dbp >= T["bp_diastolic_elevated"])
    low = sbp is not None and sbp < T["bp_systolic_low"]

    # Evidence key: the component that crossed the threshold (systolic preferred).
    def _bp_key(sys_thr: float, dia_thr: float) -> Tuple[str, str]:
        if sbp is not None and sbp >= sys_thr:
            return K_BP_SYS
        if dbp is not None and dbp >= dia_thr:
            return K_BP_DIA
        return K_BP_SYS

    key = _bp_key(T["bp_systolic_severe"], T["bp_diastolic_severe"]) if severe else _bp_key(
        T["bp_systolic_elevated"], T["bp_diastolic_elevated"]
    )

    if severe:
        ctx.add(Flag(
            code="severe_hypertension", name="Severe hypertension", severity=SEV_SEVERE, weight=0.35,
            domain=DOMAIN_MATERNAL, section=key[0], factor=key[1], observed=bp_txt,
            finding=f"Blood pressure: {bp_txt} (⚠️ Severely Elevated, ≥160/110)",
            reason=f"Blood pressure {bp_txt} is in the severe range (≥160 systolic or ≥110 diastolic) and warrants urgent clinician review.",
            action="Severe-range blood pressure warrants urgent clinician review; consider evaluation for severe pre-eclampsia features per local protocol.",
        ))
    elif elevated:
        ctx.add(Flag(
            code="hypertension", name="Elevated blood pressure", severity=SEV_WARNING, weight=0.20,
            domain=DOMAIN_MATERNAL, section=key[0], factor=key[1], observed=bp_txt,
            finding=f"Blood pressure: {bp_txt} (⚠️ Elevated, ≥140/90)",
            reason=f"Blood pressure {bp_txt} is at or above 140/90 mmHg, which may indicate a hypertensive disorder of pregnancy.",
            action="Consider repeating the blood pressure measurement and evaluating for hypertensive disorders of pregnancy.",
        ))
    elif low:
        ctx.add(Flag(
            code="hypotension", name="Low systolic blood pressure", severity=SEV_WARNING, weight=0.15,
            domain=DOMAIN_MATERNAL, section=K_BP_SYS[0], factor=K_BP_SYS[1], observed=bp_txt,
            finding=f"Blood pressure: {bp_txt} (⚠️ Low systolic, <90)",
            reason=f"Systolic blood pressure {_fmt(sbp)} mmHg is below 90 mmHg and warrants clinician review, particularly if bleeding or tachycardia is present.",
            action="Consider evaluating low blood pressure together with pulse, bleeding and hydration status.",
        ))
    else:
        ctx.normal.append(f"Blood pressure: {bp_txt} (Normal range)")


def _eval_pulse(ctx: _Ctx) -> None:
    lv = ctx.get(K_PULSE)  # maternal pulse ONLY -- fetal HR is handled separately
    hr = _num(lv.value) if lv else None
    if hr is None:
        return
    ctx.evaluated += 1
    T = THRESHOLDS
    obs = f"{_fmt(hr)} bpm"
    if hr >= T["pulse_tachycardia_severe"]:
        ctx.add(Flag(
            code="maternal_tachycardia_severe", name="Marked maternal tachycardia", severity=SEV_SEVERE, weight=0.20,
            domain=DOMAIN_MATERNAL, section=K_PULSE[0], factor=K_PULSE[1], observed=obs,
            finding=f"Maternal pulse rate: {obs} (⚠️ Markedly Elevated, ≥120)",
            reason=f"Maternal pulse {obs} is 120 bpm or above and warrants urgent clinician review.",
            action="Consider evaluating marked maternal tachycardia for infection, anemia, bleeding or other causes.",
        ))
    elif hr >= T["pulse_tachycardia"]:
        ctx.add(Flag(
            code="maternal_tachycardia", name="Maternal tachycardia", severity=SEV_WARNING, weight=0.10,
            domain=DOMAIN_MATERNAL, section=K_PULSE[0], factor=K_PULSE[1], observed=obs,
            finding=f"Maternal pulse rate: {obs} (⚠️ Elevated, ≥100)",
            reason=f"Maternal pulse {obs} is 100 bpm or above.",
            action="Consider evaluating maternal tachycardia (infection, anemia, bleeding or other causes).",
        ))
    elif hr < T["pulse_bradycardia"]:
        ctx.add(Flag(
            code="maternal_bradycardia", name="Maternal bradycardia", severity=SEV_WARNING, weight=0.10,
            domain=DOMAIN_MATERNAL, section=K_PULSE[0], factor=K_PULSE[1], observed=obs,
            finding=f"Maternal pulse rate: {obs} (⚠️ Low, <50)",
            reason=f"Maternal pulse {obs} is below 50 bpm.",
            action="Consider clinician review of maternal bradycardia.",
        ))
    else:
        ctx.normal.append(f"Maternal pulse rate: {obs} (Normal range)")


