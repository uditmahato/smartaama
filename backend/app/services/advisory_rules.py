def _combination_rules(ctx: _Ctx) -> Tuple[List[str], str]:
    """
    Returns (extra_reason_lines, floor_level) where floor_level is the minimum
    overall risk level implied by combinations of flags.
    """
    reasons: List[str] = []
    floor = RISK_LOW

    def raise_to(level: str) -> None:
        nonlocal floor
        if RISK_LEVELS.index(level) > RISK_LEVELS.index(floor):
            floor = level

    proteinuria = ctx.has("proteinuria", "proteinuria_significant", "proteinuria_24h", "proteinuria_pcr")
    symptoms = ctx.has("preeclampsia_symptoms")
    severe_bp = ctx.has("severe_hypertension")
    elevated_bp = ctx.has("hypertension")
    tachy = ctx.has("maternal_tachycardia", "maternal_tachycardia_severe")

    if severe_bp and (proteinuria or symptoms):
        raise_to(RISK_CRITICAL)
        reasons.append(
            "Severe-range blood pressure together with proteinuria and/or headache, epigastric pain or visual symptoms "
            "may indicate severe pre-eclampsia features; urgent clinician review and consideration of immediate referral is advised."
        )
    elif elevated_bp and (proteinuria or symptoms):
        raise_to(RISK_HIGH)
        reasons.append(
            "Raised blood pressure together with proteinuria and/or symptoms may indicate pre-eclampsia; "
            "early clinician review and consideration of referral is advised."
        )

    if ctx.has("vaginal_bleeding") and (tachy or ctx.has("hypotension")):
        raise_to(RISK_HIGH)
        reasons.append(
            "Reported vaginal bleeding together with tachycardia or low blood pressure may indicate significant blood loss; "
            "urgent clinician review is advised."
        )

    if ctx.has("fever") and tachy:
        raise_to(RISK_HIGH)
        reasons.append(
            "Fever together with maternal tachycardia may indicate infection; urgent clinician review is advised."
        )

    if ctx.has("severe_hypertension") and ctx.has("thrombocytopenia", "thrombocytopenia_severe"):
        raise_to(RISK_CRITICAL)
        reasons.append(
            "Severe-range blood pressure together with a low platelet count may indicate severe pre-eclampsia/HELLP features; "
            "urgent clinician review is advised."
        )

    # Several concurrent warning-level maternal findings
    maternal_warnings = [
        f for f in ctx.flags
        if f.domain == DOMAIN_MATERNAL and _SEV_RANK[f.severity] >= _SEV_RANK[SEV_WARNING]
    ]
    if len(maternal_warnings) >= 3:
        raise_to(RISK_HIGH)
        reasons.append(
            f"{len(maternal_warnings)} concurrent maternal findings are outside the rule thresholds; "
            "early clinician review and consideration of referral is advised."
        )

    return reasons, floor


def _level_from_flags(flags: Iterable[Flag]) -> str:
    worst = SEV_INFO
    any_flag = False
    for f in flags:
        any_flag = True
        if _SEV_RANK[f.severity] > _SEV_RANK[worst]:
            worst = f.severity
    if not any_flag:
        return RISK_LOW
    return {
        SEV_INFO: RISK_LOW,
        SEV_WARNING: RISK_MEDIUM,
        SEV_SEVERE: RISK_HIGH,
        SEV_CRITICAL: RISK_CRITICAL,
    }[worst]


def _max_level(a: str, b: str) -> str:
    return a if RISK_LEVELS.index(a) >= RISK_LEVELS.index(b) else b


