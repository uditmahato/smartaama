@dataclass(frozen=True)
class LatestValue:
    """A latest recorded value with (optional) clinical time."""
    value: Any
    event_time: Optional[datetime] = None


@dataclass(frozen=True)
class Flag:
    """One triggered rule."""
    code: str                       # machine code, e.g. "severe_hypertension"
    name: str                       # short human name, e.g. "Severe hypertension"
    severity: str                   # info | warning | severe | critical
    weight: float                   # contribution to referral score
    domain: str                     # maternal | fetal | history
    section: str                    # evidence key
    factor: str
    observed: str                   # display value, e.g. "165 mmHg"
    finding: str                    # advisory sentence (frontend key_findings)
    reason: Optional[str] = None    # advisory referral reason (None for info)
    action: Optional[str] = None    # advisory action (None if not applicable)

    @property
    def key(self) -> Tuple[str, str]:
        return (self.section, self.factor)


@dataclass
class RuleResult:
    risk_level: str
    flags: List[Flag] = field(default_factory=list)
    normal_findings: List[str] = field(default_factory=list)
    actions: List[str] = field(default_factory=list)
    explanation_lines: List[str] = field(default_factory=list)
    referral_recommended: bool = False
    referral_urgency: str = URGENCY_LOW
    referral_score: float = 0.0
    referral_reasons: List[str] = field(default_factory=list)
    data_points_evaluated: int = 0
    engine: str = ENGINE_VERSION
    disclaimer: str = DISCLAIMER

    # Convenience views ----------------------------------------------------
    @property
    def flag_keys(self) -> List[Tuple[str, str]]:
        return [f.key for f in self.flags]

    def flags_at_least(self, severity: str) -> List[Flag]:
        return [f for f in self.flags if _SEV_RANK[f.severity] >= _SEV_RANK[severity]]

    def all_texts(self) -> List[str]:
        """Every human-facing string (used to validate advisory language)."""
        out: List[str] = []
        for f in self.flags:
            out.append(f.finding)
            if f.reason:
                out.append(f.reason)
            if f.action:
                out.append(f.action)
        out.extend(self.normal_findings)
        out.extend(self.actions)
        out.extend(self.explanation_lines)
        out.extend(self.referral_reasons)
        out.append(self.disclaimer)
        return out


