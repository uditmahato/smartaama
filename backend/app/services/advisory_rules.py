def evaluate_latest_values(
    latest: Mapping[Tuple[str, str], Any],
    *,
    patient_age: Optional[int] = None,
) -> RuleResult:
    """
    Evaluate the LATEST value per (section, factor) and return a RuleResult.

    `latest` values may be:
      - `LatestValue(value, event_time)`
      - the stored ClinicalEvent payload dict `{"value": ..., "unit": ..., "type": ...}`
      - a raw scalar (number / bool / str)

    Only keys defined in `RULE_INPUT_KEYS` are read; anything else is ignored.
    The function is deterministic and side-effect free.
    """
    ctx = _Ctx(latest)

    _eval_blood_pressure(ctx)
    _eval_pulse(ctx)
    _eval_temperature(ctx)
    _eval_respiratory_rate(ctx)
    _eval_bmi(ctx)
    _eval_hemoglobin(ctx)
    _eval_glucose(ctx)
    _eval_platelets(ctx)
    _eval_proteinuria(ctx)
    _eval_symptoms(ctx)
    _eval_general(ctx)
    _eval_fetal_heart_rate(ctx)
    _eval_history(ctx, patient_age)

    combo_reasons, floor = _combination_rules(ctx)

    if ctx.evaluated == 0:
        level = RISK_UNKNOWN
    else:
        level = _max_level(_level_from_flags(ctx.flags), floor)

    # Order flags: most severe first, then heaviest weight
    flags = sorted(ctx.flags, key=lambda f: (-_SEV_RANK[f.severity], -f.weight, f.code))

    # Actions (de-duplicated, order preserved)
    actions: List[str] = []
    for f in flags:
        if f.action and f.action not in actions:
            actions.append(f.action)

    # Referral logic (from level, not from score)
    referral_recommended = level in (RISK_MEDIUM, RISK_HIGH, RISK_CRITICAL)
    urgency = {
        RISK_CRITICAL: URGENCY_CRITICAL,
        RISK_HIGH: URGENCY_HIGH,
        RISK_MEDIUM: URGENCY_MEDIUM,
    }.get(level, URGENCY_LOW)

    score = min(REFERRAL_SCORE_CAP, round(sum(f.weight for f in flags), 2))

    reasons: List[str] = list(combo_reasons)
    for f in flags:
        if f.reason and _SEV_RANK[f.severity] >= _SEV_RANK[SEV_WARNING] and f.reason not in reasons:
            reasons.append(f.reason)

    explanation: List[str] = []
    if level == RISK_UNKNOWN:
        explanation.append(
            "No clinical measurements that the advisory rules evaluate have been recorded for this patient yet, "
            "so an overall risk level cannot be estimated. Recording vitals, investigations and ANC findings "
            "allows the rules to run."
        )
        reasons = [
            "No clinical measurements are recorded yet; the advisory rules cannot evaluate referral need until data is entered."
        ]
    else:
        explanation.extend(combo_reasons)
        for f in flags:
            explanation.append(f.finding)
        if not flags:
            explanation.append(
                "The latest recorded values did not cross any advisory rule threshold. This does not exclude risk; "
                "the assessment is limited by data completeness and recency."
            )
            reasons = [
                "No findings outside the rule thresholds were detected in the latest recorded values; "
                "routine antenatal follow-up may continue with clinician review as usual."
            ]
        elif not referral_recommended:
            reasons = [
                "Only low-severity or contextual findings were detected in the latest recorded values; "
                "routine antenatal follow-up may continue with clinician review as usual."
            ]

    result = RuleResult(
        risk_level=level,
        flags=flags,
        normal_findings=list(ctx.normal),
        actions=actions,
        explanation_lines=explanation,
        referral_recommended=referral_recommended,
        referral_urgency=urgency,
        referral_score=score,
        referral_reasons=reasons,
        data_points_evaluated=ctx.evaluated,
    )

    # Guardrail: every human-facing string is advisory.
    for text in result.all_texts():
        validate_advisory_language(text)

    return result


def build_summary_text(result: RuleResult, *, age: Optional[Any] = None, event_count: int = 0) -> str:
    """Short clinician-facing summary sentence used by both engines."""
    who = f"Patient ({age} years)" if age not in (None, "", "Unknown") else "Patient"
    warn = result.flags_at_least(SEV_WARNING)
    if result.risk_level == RISK_UNKNOWN:
        return (
            f"{who}: no clinical measurements have been recorded yet, so the advisory rules could not "
            "estimate a risk level. Assessment pending data entry."
        )
    if warn:
        return (
            f"{who}: {len(warn)} finding(s) outside advisory rule thresholds in the latest recorded values "
            f"({event_count} clinical entries reviewed). Overall advisory risk level: {result.risk_level}. "
            "Clinician review is advised."
        )
    if result.flags:
        return (
            f"{who}: only low-severity or contextual findings in the latest recorded values "
            f"({event_count} clinical entries reviewed). Overall advisory risk level: {result.risk_level}."
        )
    return (
        f"{who}: latest recorded values are within advisory rule thresholds "
        f"({event_count} clinical entries reviewed). Overall advisory risk level: {result.risk_level}."
    )


