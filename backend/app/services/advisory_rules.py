"""
Rule-based maternal advisory engine (single source of truth for thresholds).

This module is PURE: no database, no settings, no network. It takes the
*latest recorded value per (section, factor)* and returns deterministic,
explainable flags, an overall risk level, advisory actions and a referral
suggestion.

Both public engines build on `evaluate_latest_values`:
- `app.services.risk_engine.RiskEngine`      -> POST /ai/risk
- `app.services.ai_patient_service`          -> /ai-analysis/* (frontend cards)

Section / factor keys are the ones defined in `app.models.medical_schema`
(`MEDICAL_SCHEMA`). Do not read keys that the schema does not define.

Vocabulary (stable; the frontend depends on these values):
- risk level : unknown | low | medium | high | critical
- urgency    : low | medium | high | critical
- severity   : info | warning | severe | critical   (per flag)

Nothing here is a diagnosis. Every string is advisory and is checked with
`app.ai.validators.validate_advisory_language`.
"""

