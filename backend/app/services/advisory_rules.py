def _coerce_latest(raw: Any) -> LatestValue:
    """Accept LatestValue, a stored payload dict ({"value": ..}), or a raw scalar."""
    if isinstance(raw, LatestValue):
        return raw
    if isinstance(raw, dict) and "value" in raw:
        et = raw.get("event_time")
        return LatestValue(value=raw.get("value"), event_time=et if isinstance(et, datetime) else None)
    return LatestValue(value=raw, event_time=None)


def _num(v: Any) -> Optional[float]:
    if v is None or isinstance(v, bool):
        return None
    if isinstance(v, (int, float)):
        f = float(v)
        return f if math.isfinite(f) else None
    if isinstance(v, dict) and "value" in v:
        return _num(v.get("value"))
    if isinstance(v, str):
        s = v.strip().replace(",", "")
        if not s:
            return None
        try:
            f = float(s)
        except ValueError:
            return None
        return f if math.isfinite(f) else None
    return None


def _bool(v: Any) -> Optional[bool]:
    if v is None:
        return None
    if isinstance(v, bool):
        return v
    if isinstance(v, (int, float)):
        if v == 1:
            return True
        if v == 0:
            return False
        return None
    if isinstance(v, dict) and "value" in v:
        return _bool(v.get("value"))
    if isinstance(v, str):
        s = v.strip().lower()
        if s in {"true", "yes", "y", "1", "present"}:
            return True
        if s in {"false", "no", "n", "0", "absent"}:
            return False
    return None


def _text(v: Any) -> Optional[str]:
    if v is None:
        return None
    if isinstance(v, dict) and "value" in v:
        return _text(v.get("value"))
    if isinstance(v, str):
        s = v.strip()
        return s or None
    return str(v)


def _fmt(n: float) -> str:
    return str(int(n)) if float(n).is_integer() else f"{n:g}"


def _sort_time(dt: Optional[datetime]) -> datetime:
    """Sortable time; None sorts oldest, naive treated as UTC."""
    if dt is None:
        return datetime.min.replace(tzinfo=timezone.utc)
    if dt.tzinfo is None:
        return dt.replace(tzinfo=timezone.utc)
    return dt


def _dipstick_grade(v: Any) -> Optional[float]:
    """
    Map dipstick protein enum to a numeric grade:
      Negative -> 0, Trace -> 0.5, + -> 1, ++ -> 2, +++ -> 3, ++++ -> 4
    Returns None when unrecognised.
    """
    s = _text(v)
    if s is None:
        return None
    s = s.strip().lower()
    table = {
        "negative": 0.0, "neg": 0.0, "nil": 0.0, "none": 0.0, "-": 0.0, "0": 0.0,
        "trace": 0.5,
        "+": 1.0, "1+": 1.0, "positive": 1.0,
        "++": 2.0, "2+": 2.0,
        "+++": 3.0, "3+": 3.0,
        "++++": 4.0, "4+": 4.0,
    }
    return table.get(s)


